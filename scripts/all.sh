#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FINETUNE_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

# Where the OpenFold3 repo lives. Override before running if needed, e.g.
# OPENFOLD_REPO_ROOT=/path/to/openfold3 ./scripts/all.sh
OPENFOLD_REPO_ROOT="${OPENFOLD_REPO_ROOT:-$FINETUNE_ROOT/../openfold3-internal}"

# Specify output directory
DATASET_ROOT="${DATASET_ROOT:-$FINETUNE_ROOT/example/dataset}"
# Specify inputs 
INPUT_DIR="$DATASET_ROOT/input_structures" # fragalysis data in PDB and SDF format
SPLIT_DIR="$DATASET_ROOT/input_splits" # contains train_ids.txt and val_ids.txt with the IDs to use for training and validation splits
TRAIN_DATASET_NAME="a71ev2a-small-test"
VAL_DATASET_NAME="a71ev2a-small-test-val"

# Main folders that will be generated and used in the pipeline
MONOMER_CIF_DIR="$DATASET_ROOT/merged_cifs_monomer"
PREPROCESSED_DIR="$DATASET_ROOT/preprocessed"
ALIGNMENTS_DIR="$DATASET_ROOT/alignments"
CACHE_DIR="$DATASET_ROOT/caches"
MERGED_CIF_DIR="$DATASET_ROOT/merged_cifs"
MSA_QUERY_DIR="$DATASET_ROOT/msa_queries"
ALIGNMENT_ARRAY_DIR="$DATASET_ROOT/alignment_arrays"

# Subfiles and paths that will be generated and used in the pipeline 
CCD_CIF="$MERGED_CIF_DIR/reference_data/components_harmonized.cif"
CCD_BCIF="$MERGED_CIF_DIR/reference_data/components_harmonized.bcif"
MONOMER_LOG_PATH="$MONOMER_CIF_DIR/process_into_monomer.log"
PREPROCESSED_STRUCTURE_DIR="$PREPROCESSED_DIR/structure_files"
METADATA_CACHE="$PREPROCESSED_DIR/metadata.json"
REPRESENTATIVES_FASTA="$ALIGNMENTS_DIR/alignment_representatives.fasta"
ALIGNMENT_REPRESENTATIVES_REPORT_JSON="$ALIGNMENTS_DIR/alignment_representatives_report.json"
MSA_GENERATION_REPORT_JSON="$ALIGNMENTS_DIR/msa_generation_report.json"
ALIGNMENTS_MAIN_DIR="$ALIGNMENTS_DIR/main"
TRAIN_IDS="$SPLIT_DIR/train_ids.txt"
VAL_IDS="$SPLIT_DIR/val_ids.txt"
TRAIN_METADATA_OUTPUT="$PREPROCESSED_DIR/metadata_train.json"
VAL_METADATA_OUTPUT="$PREPROCESSED_DIR/metadata_val.json"
TRAIN_CACHE_OUTPUT="$CACHE_DIR/train_cache.json"
MISSING_ALIGNMENT_LOG="$CACHE_DIR/missing_alignments.json"
TRAIN_CACHE_LOG_FILE="$CACHE_DIR/create_train_cache.log"
VAL_CACHE_OUTPUT="$CACHE_DIR/val_cache.json"

# Uses: OPENFOLD_REPO_ROOT, DATASET_ROOT, INPUT_DIR, MERGED_CIF_DIR
OPENFOLD_REPO_ROOT="$OPENFOLD_REPO_ROOT" DATASET_ROOT="$DATASET_ROOT" INPUT_DIR="$INPUT_DIR" MERGED_CIF_DIR="$MERGED_CIF_DIR" \
  "$SCRIPT_DIR/01_merge_pdb_sdfs_to_cif.sh"

# Uses: OPENFOLD_REPO_ROOT, DATASET_ROOT, MERGED_CIF_DIR, CCD_CIF, CCD_BCIF
OPENFOLD_REPO_ROOT="$OPENFOLD_REPO_ROOT" DATASET_ROOT="$DATASET_ROOT" MERGED_CIF_DIR="$MERGED_CIF_DIR" CCD_CIF="$CCD_CIF" CCD_BCIF="$CCD_BCIF" \
  "$SCRIPT_DIR/02_convert_augmented_ccd_to_biotite_bcif.sh"

# Uses: OPENFOLD_REPO_ROOT, DATASET_ROOT, MERGED_CIF_DIR, MONOMER_CIF_DIR, MONOMER_LOG_PATH
OPENFOLD_REPO_ROOT="$OPENFOLD_REPO_ROOT" DATASET_ROOT="$DATASET_ROOT" MERGED_CIF_DIR="$MERGED_CIF_DIR" MONOMER_CIF_DIR="$MONOMER_CIF_DIR" MONOMER_LOG_PATH="$MONOMER_LOG_PATH" \
  "$SCRIPT_DIR/03_process_into_monomer.sh"

# Uses: OPENFOLD_REPO_ROOT, DATASET_ROOT, MONOMER_CIF_DIR, MERGED_CIF_DIR, CCD_CIF, CCD_BCIF, PREPROCESSED_DIR
OPENFOLD_REPO_ROOT="$OPENFOLD_REPO_ROOT" DATASET_ROOT="$DATASET_ROOT" MONOMER_CIF_DIR="$MONOMER_CIF_DIR" MERGED_CIF_DIR="$MERGED_CIF_DIR" CCD_CIF="$CCD_CIF" CCD_BCIF="$CCD_BCIF" PREPROCESSED_DIR="$PREPROCESSED_DIR" \
  "$SCRIPT_DIR/04_preprocess_openfold3_structures.sh"

# Uses: OPENFOLD_REPO_ROOT, DATASET_ROOT, PREPROCESSED_DIR, PREPROCESSED_STRUCTURE_DIR, ALIGNMENTS_DIR, REPRESENTATIVES_FASTA, ALIGNMENT_REPRESENTATIVES_REPORT_JSON
OPENFOLD_REPO_ROOT="$OPENFOLD_REPO_ROOT" DATASET_ROOT="$DATASET_ROOT" PREPROCESSED_DIR="$PREPROCESSED_DIR" PREPROCESSED_STRUCTURE_DIR="$PREPROCESSED_STRUCTURE_DIR" ALIGNMENTS_DIR="$ALIGNMENTS_DIR" REPRESENTATIVES_FASTA="$REPRESENTATIVES_FASTA" ALIGNMENT_REPRESENTATIVES_REPORT_JSON="$ALIGNMENT_REPRESENTATIVES_REPORT_JSON" \
  "$SCRIPT_DIR/05_build_msa_representatives.sh"

# Uses: OPENFOLD_REPO_ROOT, DATASET_ROOT, ALIGNMENTS_DIR, REPRESENTATIVES_FASTA, MSA_QUERY_DIR, MSA_GENERATION_REPORT_JSON
OPENFOLD_REPO_ROOT="$OPENFOLD_REPO_ROOT" DATASET_ROOT="$DATASET_ROOT" ALIGNMENTS_DIR="$ALIGNMENTS_DIR" REPRESENTATIVES_FASTA="$REPRESENTATIVES_FASTA" MSA_QUERY_DIR="$MSA_QUERY_DIR" MSA_GENERATION_REPORT_JSON="$MSA_GENERATION_REPORT_JSON" \
  "$SCRIPT_DIR/06_generate_colabfold_msas.sh"

# Uses: OPENFOLD_REPO_ROOT, DATASET_ROOT, ALIGNMENTS_DIR, ALIGNMENTS_MAIN_DIR, ALIGNMENT_ARRAY_DIR
OPENFOLD_REPO_ROOT="$OPENFOLD_REPO_ROOT" DATASET_ROOT="$DATASET_ROOT" ALIGNMENTS_DIR="$ALIGNMENTS_DIR" ALIGNMENTS_MAIN_DIR="$ALIGNMENTS_MAIN_DIR" ALIGNMENT_ARRAY_DIR="$ALIGNMENT_ARRAY_DIR" \
  "$SCRIPT_DIR/07_preparse_alignment_arrays.sh"

# Uses: OPENFOLD_REPO_ROOT, DATASET_ROOT, PREPROCESSED_DIR, METADATA_CACHE, SPLIT_DIR, TRAIN_IDS, VAL_IDS, TRAIN_METADATA_OUTPUT, VAL_METADATA_OUTPUT
OPENFOLD_REPO_ROOT="$OPENFOLD_REPO_ROOT" DATASET_ROOT="$DATASET_ROOT" PREPROCESSED_DIR="$PREPROCESSED_DIR" METADATA_CACHE="$METADATA_CACHE" SPLIT_DIR="$SPLIT_DIR" TRAIN_IDS="$TRAIN_IDS" VAL_IDS="$VAL_IDS" TRAIN_METADATA_OUTPUT="$TRAIN_METADATA_OUTPUT" VAL_METADATA_OUTPUT="$VAL_METADATA_OUTPUT" \
  "$SCRIPT_DIR/08_materialize_split_metadata.sh"

# Uses: OPENFOLD_REPO_ROOT, DATASET_ROOT, PREPROCESSED_DIR, PREPROCESSED_STRUCTURE_DIR, ALIGNMENTS_DIR, REPRESENTATIVES_FASTA, CACHE_DIR, TRAIN_METADATA_CACHE, TRAIN_CACHE_OUTPUT, MISSING_ALIGNMENT_LOG, TRAIN_CACHE_LOG_FILE, TRAIN_DATASET_NAME
OPENFOLD_REPO_ROOT="$OPENFOLD_REPO_ROOT" DATASET_ROOT="$DATASET_ROOT" PREPROCESSED_DIR="$PREPROCESSED_DIR" PREPROCESSED_STRUCTURE_DIR="$PREPROCESSED_STRUCTURE_DIR" ALIGNMENTS_DIR="$ALIGNMENTS_DIR" REPRESENTATIVES_FASTA="$REPRESENTATIVES_FASTA" CACHE_DIR="$CACHE_DIR" TRAIN_METADATA_CACHE="$TRAIN_METADATA_OUTPUT" TRAIN_CACHE_OUTPUT="$TRAIN_CACHE_OUTPUT" MISSING_ALIGNMENT_LOG="$MISSING_ALIGNMENT_LOG" TRAIN_CACHE_LOG_FILE="$TRAIN_CACHE_LOG_FILE" TRAIN_DATASET_NAME="$TRAIN_DATASET_NAME" \
  "$SCRIPT_DIR/09_create_weighted_training_cache.sh"

# Uses: OPENFOLD_REPO_ROOT, DATASET_ROOT, PREPROCESSED_DIR, PREPROCESSED_STRUCTURE_DIR, ALIGNMENTS_DIR, REPRESENTATIVES_FASTA, ALIGNMENT_ARRAY_DIR, CACHE_DIR, VAL_METADATA_CACHE, VAL_CACHE_OUTPUT, VAL_DATASET_NAME
OPENFOLD_REPO_ROOT="$OPENFOLD_REPO_ROOT" DATASET_ROOT="$DATASET_ROOT" PREPROCESSED_DIR="$PREPROCESSED_DIR" PREPROCESSED_STRUCTURE_DIR="$PREPROCESSED_STRUCTURE_DIR" ALIGNMENTS_DIR="$ALIGNMENTS_DIR" REPRESENTATIVES_FASTA="$REPRESENTATIVES_FASTA" ALIGNMENT_ARRAY_DIR="$ALIGNMENT_ARRAY_DIR" CACHE_DIR="$CACHE_DIR" VAL_METADATA_CACHE="$VAL_METADATA_OUTPUT" VAL_CACHE_OUTPUT="$VAL_CACHE_OUTPUT" VAL_DATASET_NAME="$VAL_DATASET_NAME" \
  "$SCRIPT_DIR/10_create_full_validation_cache.sh"
